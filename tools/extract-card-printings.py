"""Resolve alternate printings of packaged cards from reference CardDef declarations."""
import argparse
import json
import re
from pathlib import Path


definition = re.compile(r'^([a-z]\w*)\s*::\s*CardDef\s*$', re.M)
constructor = re.compile(
    r'\b(?:asset|event|skill|weakness|treachery|basicWeakness|investigator|emptyCardDef)\s+"([0-9]{5}[a-z]?)"'
)
alternates = re.compile(r'(?:cdAlternateCardCodes\s*=|withAlternates)\s*\[([^]]*)\]|withAlternate\s+"([^"]+)"')


def extract(source, packaged):
    backend = source / 'backend/arkham-api/library/Arkham'
    directories = ('Asset/Cards', 'Event/Cards', 'Skill/CardDefs', 'Treachery/CardDefs')
    files = [backend / 'Investigator/Cards.hs']
    for directory in directories:
        files.extend(sorted((backend / directory).rglob('*.hs')))
    rows = {}
    for path in files:
        text = path.read_text(encoding='utf-8')
        if 'cdAlternateCardCodes' not in text and 'withAlternate' not in text:
            continue
        declarations = list(definition.finditer(text))
        for index, match in enumerate(declarations):
            end = declarations[index + 1].start() if index + 1 < len(declarations) else len(text)
            body = text[match.end():end]
            codes = constructor.findall(body)
            if len(codes) != 1 or codes[0] not in packaged:
                continue
            for group, single in alternates.findall(body):
                for alias in [single] if single else re.findall(r'"([0-9]{5}[a-z]?)"', group):
                    if alias in packaged or (alias in rows and rows[alias]['canonical'] != codes[0]):
                        raise ValueError(f'conflicting alternate printing {alias}')
                    rows[alias] = {'canonical': codes[0], 'symbol': match[1],
                                   'source': path.relative_to(source).as_posix()}
    return dict(sorted(rows.items()))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    packaged = json.loads((root / 'dist/cards.json').read_bytes())
    rows = extract(args.source.resolve(), packaged)
    if not rows:
        raise ValueError('No alternate printings found.')
    output = '// Generated by tools/extract-card-printings.py from CardDef declarations.\n'
    output += 'export const alternatePrintings = ' + json.dumps(rows, indent=1) + ';\n'
    (root / 'dist/card-printings.js').write_text(output, encoding='utf-8', newline='\n')
    print(f'Indexed {len(rows)} alternate printings of packaged cards.')


if __name__ == '__main__':
    main()
